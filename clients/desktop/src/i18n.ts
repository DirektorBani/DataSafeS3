export type DesktopLocale = keyof typeof resources;

function storedLocale(): DesktopLocale {
  const saved = localStorage.getItem(LOCALE_KEY);
  return saved === "ru" ? "ru" : "en";
}

void i18n.use(initReactI18next).init({
  resources: {
    en: { ...resources.en, common: enCommon, nav: enNav, buckets: enBuckets, bucketDetail: enBucketDetail },
    ru: { ...resources.ru, common: ruCommon, nav: ruNav, buckets: ruBuckets, bucketDetail: ruBucketDetail },
  },
  lng: storedLocale(),
  fallbackLng: "en",
  ns: ["shell", "common", "nav", "buckets", "bucketDetail"],
  defaultNS: "shell",
  interpolation: { escapeValue: false },
});

export function setDesktopLocale(locale: DesktopLocale, persist = true) {
  localStorage.setItem(LOCALE_KEY, locale);
  void i18n.changeLanguage(locale);
  document.documentElement.lang = locale;
  if (persist) {
    void saveSettings({ locale }).catch(() => undefined);
  }
}

export default i18n;
